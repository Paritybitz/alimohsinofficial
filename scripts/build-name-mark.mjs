/**
 * Builds the "ALI MOHSIN." wordmark as one vector path, set in Bruno Ace
 * (SIL Open Font License) exactly as the font draws it — no changes to the
 * letterforms. Drawing it as a path lets the name take the brushed-metal fill.
 *
 *   npm run name-mark   → writes src/data/nameMark.ts
 */
import { readFileSync, writeFileSync } from 'node:fs'
import opentype from 'opentype.js'

const TEXT = 'ALI MOHSIN.'
const FONT = new URL('./fonts/BrunoAce-Regular.woff', import.meta.url)
const TRACKING = 0 // extra letter spacing in font units; 0 = the font's own spacing

const buf = readFileSync(FONT)
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength))
const size = font.unitsPerEm

// Plain capitals need no shaping, so map each character to its glyph directly.
const glyphs = [...TEXT].map((ch) => font.charToGlyph(ch))
const path = new opentype.Path()
let x = 0
glyphs.forEach((glyph, i) => {
  path.extend(glyph.getPath(x, 0, size))
  x += glyph.advanceWidth + TRACKING
  if (i < glyphs.length - 1) x += font.getKerningValue(glyph, glyphs[i + 1])
})

// Shift so the drawing starts at 0,0 with a tight box.
const box = path.getBoundingBox()
const r = (n) => Math.round(n * 10) / 10
for (const c of path.commands) {
  for (const [kx, ky] of [['x', 'y'], ['x1', 'y1'], ['x2', 'y2']]) {
    if (c[kx] !== undefined) {
      c[kx] = r(c[kx] - box.x1)
      c[ky] = r(c[ky] - box.y1)
    }
  }
}
const width = r(box.x2 - box.x1)
const height = r(box.y2 - box.y1)
const d = path.toPathData(1)

writeFileSync(
  new URL('../src/data/nameMark.ts', import.meta.url),
  `/**
 * "ALI MOHSIN." in Bruno Ace, converted to a vector path.
 * Generated by scripts/build-name-mark.mjs — run \`npm run name-mark\`
 * after changing the wording or spacing there, rather than editing this file.
 */
export const nameMark = {
  width: ${width},
  height: ${height},
  d: '${d}',
}
`,
)
console.log(`nameMark: ${width} × ${height}, ${d.length} chars`)
